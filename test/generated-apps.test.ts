// Sprint 71: generated applications read like APEX's (migration 097):
// human labels (abbreviations, run-together words, comments, plural and
// singular), foreign keys shown by their parent's name in reports, file
// columns as one upload item, number format masks, "(none)" and top-N
// charts, and the edit icon of a report row.
import { after, before, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import type { FastifyInstance } from 'fastify';
import '../src/env.ts';
import { buildApp } from '../src/app.ts';
import { closePools, owner } from '../src/db.ts';
import { topRows } from '../src/runtime/regions.ts';
import type { Region } from '../src/metadata.ts';
import { Browser, formFields } from './helpers.ts';

let app: FastifyInstance;
let appId: number;
const alias = 'gen-s71';
const ROLE = 'pgkiln_s71_gen';
const SCHEMA = 'gen71';

before(async () => {
  app = await buildApp({ logger: false });
  await owner.query(`delete from meta.app where alias = $1`, [alias]);
  await owner.query(`drop schema if exists ${SCHEMA} cascade`);
  await owner.query(`drop owned by ${ROLE}`).catch(() => undefined);
  await owner.query(`drop role if exists ${ROLE}`);
  await owner.query(`create role ${ROLE} nologin`);
  await owner.query(`grant ${ROLE} to pgkiln_runtime`);
  await owner.query(`create schema ${SCHEMA}`);
  await owner.query(`
    create table ${SCHEMA}.dept (deptno int primary key, dname text not null, loc text);
    create table ${SCHEMA}.emp (
      empno int generated by default as identity primary key, ename text not null, job text,
      mgr int references ${SCHEMA}.emp, hiredate date, sal numeric(9,2), comm numeric(9,2), qty int,
      deptno int references ${SCHEMA}.dept,
      photo bytea, photo_name text, photo_mime text, photo_size int, photo_updated timestamptz);
    comment on table ${SCHEMA}.dept is 'Business units';
    comment on column ${SCHEMA}.emp.job is 'Job title';
    comment on column ${SCHEMA}.emp.qty is 'The number of things this employee looks after. Used by the yearly review.';
    insert into ${SCHEMA}.dept values (10, 'ACCOUNTING', 'NEW YORK'), (30, 'SALES', 'CHICAGO');
    insert into ${SCHEMA}.emp (empno, ename, job, mgr, sal, deptno) overriding system value values
      (1, 'KING', 'PRESIDENT', null, 5000, 10), (2, 'BLAKE', 'MANAGER', 1, 2850, 30), (3, 'ALLEN', 'SALESMAN', 2, 1600, 30);
    grant usage on schema ${SCHEMA} to ${ROLE};
    grant select, insert, update, delete on all tables in schema ${SCHEMA} to ${ROLE};
    grant usage on all sequences in schema ${SCHEMA} to ${ROLE};
  `);
  appId = (await owner.one(`insert into meta.app (alias, name, authentication, db_role) values ($1, 'Generated', 'none', $2) returning id`, [alias, ROLE])).id;
  await owner.query(`insert into meta.page (app_id, page_no, name, requires_auth) values ($1, 1, 'Home', false)`, [appId]);
  await owner.query(`insert into meta.nav_entry (app_id, seq, label, icon, target_page) values ($1, 1, 'Home', 'home', 1)`, [appId]);
});

after(async () => {
  await owner.query('delete from meta.app where id = $1', [appId]);
  await owner.query(`drop schema if exists ${SCHEMA} cascade`);
  await owner.query(`drop owned by ${ROLE}`);
  await owner.query(`drop role if exists ${ROLE}`);
  await app.close();
  await closePools();
});

const one = async (sql: string, params: unknown[] = []) => Object.values(await owner.one(sql, params))[0];
const generate = (kind: string, table: string, page: number, options: Record<string, unknown> = {}) =>
  owner.one('select meta.generate_page($1, $2, $3::regclass, $4, $5::jsonb) as id', [alias, kind, table, page, JSON.stringify(options)]);
const regions = async (page: number) =>
  (await owner.query(`select r.* from meta.region r join meta.page p on p.id = r.page_id where p.app_id = $1 and p.page_no = $2 order by r.seq`, [appId, page])).rows;
const publish = () => owner.query('update meta.page set requires_auth = false where app_id = $1', [appId]);

describe('labels', () => {
  test('names become words: abbreviations, run-together words, camelCase, digits', async () => {
    const cases: [string, string][] = [
      ['empno', 'Employee Number'], ['hiredate', 'Hire Date'], ['sal', 'Salary'], ['comm', 'Commission'], ['mgr', 'Manager'],
      ['deptno', 'Department Number'], ['order_qty', 'Order Quantity'], ['unitPrice', 'Unit Price'], ['address2', 'Address 2'],
      ['crm_contact', 'CRM Contact'], ['customer_id', 'Customer ID'], ['first_name', 'First Name'], ['notes', 'Notes'],
      ['banana', 'Banana'], ['created_at', 'Created At'], ['pct_done', 'Percent Done'],
    ];
    for (const [name, label] of cases) assert.equal(await one('select meta.wizard_label($1)', [name]), label, name);
  });

  test('plural and singular; uncountable words stay', async () => {
    for (const [s, p] of [['Employee', 'Employees'], ['Policy', 'Policies'], ['Status', 'Statuses'], ['Box', 'Boxes'], ['Day', 'Days'], ['Staff', 'Staff'], ['Person', 'People'], ['CRM', 'CRM']]) {
      assert.equal(await one('select meta.wizard_plural($1)', [s]), p, s);
      assert.equal(await one('select meta.wizard_singular($1)', [p]), s, p);
    }
    assert.equal(await one('select meta.wizard_plural($1)', ['Orders']), 'Orders', 'a plural already');
  });

  test('tables and columns: comments, foreign keys without their suffix, the table letter', async () => {
    assert.equal(await one(`select meta.wizard_table_label('${SCHEMA}.emp'::regclass)`), 'Employees');
    assert.equal(await one(`select meta.wizard_table_label('${SCHEMA}.emp'::regclass, false)`), 'Employee');
    assert.equal(await one(`select meta.wizard_table_label('${SCHEMA}.dept'::regclass)`), 'Business units', 'a short table comment wins');
    const labels = (await owner.query(`select column_name, meta.wizard_column_label('${SCHEMA}.emp'::regclass, column_name) as l from meta.wizard_catalog('${SCHEMA}.emp'::regclass)`)).rows;
    const l = Object.fromEntries(labels.map((r) => [r.column_name, r.l]));
    assert.deepEqual([l.empno, l.ename, l.job, l.mgr, l.hiredate, l.sal, l.comm, l.deptno], ['Employee Number', 'Name', 'Job title', 'Manager', 'Hire Date', 'Salary', 'Commission', 'Department']);
    assert.equal(l.qty, 'Quantity', 'a long comment is no label');
    assert.equal(await one(`select meta.wizard_column_label('${SCHEMA}.dept'::regclass, 'dname')`), 'Name');
    assert.equal(await one(`select meta.wizard_column_label('${SCHEMA}.dept'::regclass, 'loc')`), 'Location');
  });
});

describe('report and form', () => {
  test('foreign keys show the parent, file columns are left out, numbers get a mask, a pencil per row', async () => {
    await generate('report_form', `${SCHEMA}.emp`, 10, { form_page: 11 });
    const page = await owner.one('select name from meta.page where app_id = $1 and page_no = 10', [appId]);
    assert.equal(page.name, 'Employees');
    const form = await owner.one('select name, title from meta.page where app_id = $1 and page_no = 11', [appId]);
    assert.deepEqual([form.name, form.title], ['Employee Form', 'Employee']);
    const [r] = await regions(10);
    assert.doesNotMatch(r.source, /photo/);
    assert.match(r.source, /left join gen71\.emp p1 on p1\.empno = t\.mgr/);
    assert.match(r.source, /left join gen71\.dept p2 on p2\.deptno = t\.deptno/);
    assert.deepEqual(r.config.hidden, ['mgr', 'deptno']);
    assert.equal(r.config.headings.mgr_display, 'Manager');
    assert.equal(r.config.headings.deptno_display, 'Department');
    assert.deepEqual(r.config.formats, { sal: '999G999G999G990D00', comm: '999G999G999G990D00', qty: '999G999G999G990' });
    assert.equal(r.config.link.icon, true);
    const nav = (await owner.query('select label, icon from meta.nav_entry where app_id = $1 and target_page = 10', [appId])).rows;
    assert.deepEqual(nav, [{ label: 'Employees', icon: 'table' }]);

    await publish();
    const v = new Browser(app);
    const body = (await v.get(`/a/${alias}/10`)).body;
    assert.match(body, /<th scope="col" class="row-edit" aria-label="Edit"><\/th>/);
    assert.match(body, /<td class="row-edit"><a href="\/a\/gen-s71\/11\?P11_EMPNO=2&amp;cs=[0-9a-f]+[^"]*" [^>]*aria-label="Edit 2"/);
    assert.match(body, />BLAKE<\/td><td class="null" data-label="Job title">MANAGER|>MANAGER</);
    assert.match(body, /data-label="Manager">KING</);
    assert.match(body, /data-label="Department">SALES</);
    assert.match(body, /data-label="Salary">2,850\.00</);
    assert.doesNotMatch(body, /data-label="Mgr"|data-label="Photo/);
    // KING has no manager: an empty cell
    assert.match(body, /data-label="Manager"><\/td>/);
  });

  test('the form: one file item bound to its name, type, size and time columns; masked numbers; help from a long comment', async () => {
    const items = (await owner.query(`select i.name, i.label, i.type, i.config, i.help from meta.item i join meta.page p on p.id = i.page_id where p.app_id = $1 and p.page_no = 11 order by i.seq`, [appId])).rows;
    const by = Object.fromEntries(items.map((i) => [i.name, i]));
    assert.ok(!by.P11_PHOTO_NAME && !by.P11_PHOTO_MIME && !by.P11_PHOTO_SIZE && !by.P11_PHOTO_UPDATED, 'no fields for the file columns');
    assert.equal(by.P11_PHOTO.type, 'file');
    assert.deepEqual(by.P11_PHOTO.config, { accept: 'image/*', filename_column: 'photo_name', mime_column: 'photo_mime', size_column: 'photo_size', updated_column: 'photo_updated' });
    assert.equal(by.P11_SAL.label, 'Salary');
    assert.deepEqual(by.P11_SAL.config, { format_mask: '999G999G999G990D00' });
    assert.match(by.P11_QTY.help, /yearly review/);
    // an upload fills the name, type, size and time columns
    const v = new Browser(app);
    const list = (await v.get(`/a/${alias}/10`)).body;
    const href = /href="(\/a\/gen-s71\/11\?P11_EMPNO=3&amp;cs=[0-9a-f]+)"/.exec(list)![1].replace(/&amp;/g, '&');
    const f = (await v.get(href)).body;
    assert.match(f, /id="P11_SAL" name="P11_SAL" value="1,600\.00"/);
    const { __csrf: _csrf, ...fields } = formFields(f);
    const res = await v.upload(`/a/${alias}/11`, { ...fields, __request: 'SAVE' }, { P11_PHOTO: { name: 'allen.png', type: 'image/png', data: Buffer.from('89504e470d0a1a0a', 'hex') } });
    assert.ok([200, 303].includes(res.statusCode), res.body.slice(0, 500));
    const row = await owner.one(`select photo_name, photo_mime, photo_size, photo_updated is not null as stamped, sal from ${SCHEMA}.emp where empno = 3`);
    assert.deepEqual(row, { photo_name: 'allen.png', photo_mime: 'image/png', photo_size: 8, stamped: true, sal: '1600.00' });
  });

  test('a chart labels rows without a value "(none)" and keeps the top rows', async () => {
    await generate('chart', `${SCHEMA}.emp`, 20, { label_column: 'mgr' });
    const [r] = await regions(20);
    assert.match(r.source, /coalesce\(\(\(select p\.ename from gen71\.emp p where p\.empno = t\.mgr\)\)::text, '\(none\)'\) as "Manager"/);
    assert.equal(r.config.top, 10);
    await publish();
    assert.match((await new Browser(app).get(`/a/${alias}/20`)).body, /\(none\)/);
  });
});

describe('charts', () => {
  test('top rows: the rest summed into "Other"; other kinds and short lists keep their rows', () => {
    const rows = [['a', 9, 1], ['b', 5, 1], ['c', 3, 1], ['d', 2, 1], ['e', 1, 1]];
    const r = (config: Record<string, unknown>) => ({ config }) as unknown as Region;
    assert.deepEqual(topRows(r({ top: 3 }), 'bar', rows, 'Other'), [['a', 9, 1], ['b', 5, 1], ['Other', 6, 3]]);
    assert.equal(topRows(r({ top: 5 }), 'bar', rows, 'Other'), rows);
    assert.equal(topRows(r({ top: 3 }), 'line', rows, 'Other'), rows);
    for (const top of [1, 0, -3, 101, 'x', 2.5]) assert.equal(topRows(r({ top }), 'pie', rows, 'Other'), rows, String(top));
  });
});
