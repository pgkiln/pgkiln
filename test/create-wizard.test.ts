// Sprint 73: the Create Application wizard on one page (APEX's): a page type
// per table, features, appearance and language, straight to the new
// application; meta.app_activity for the Activity page (migration 098).
import { after, before, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import type { FastifyInstance } from 'fastify';
import '../src/env.ts';
import { buildApp } from '../src/app.ts';
import { closePools, owner } from '../src/db.ts';
import { Browser, formFields } from './helpers.ts';

let app: FastifyInstance;
const SRC = 'cw73_src';
const ALIASES = ['cw73-kinds', 'cw73-blank', 'cw73-bad'];

async function dropApp(alias: string) {
  const role = `app_${alias.replace(/-/g, '_')}`;
  await owner.query('delete from meta.app where alias = $1', [alias]);
  await owner.query(`drop schema if exists ${alias.replace(/-/g, '_')} cascade`);
  if ((await owner.query('select 1 from pg_roles where rolname = $1', [role])).rowCount) {
    await owner.query(`drop owned by ${role}`);
    await owner.query(`drop role ${role}`);
  }
}

before(async () => {
  app = await buildApp({ logger: false });
  for (const a of ALIASES) await dropApp(a);
  await owner.query(`drop schema if exists ${SRC} cascade`);
  await owner.query(`
    create schema ${SRC};
    create table ${SRC}.dept (id int primary key, name text not null);
    create table ${SRC}.emp (id int generated by default as identity primary key, name text not null, dept_id int references ${SRC}.dept, hired date);
    create table ${SRC}.note (body text);
    create view ${SRC}.emp_v as select name from ${SRC}.emp;
    insert into ${SRC}.dept values (1, 'Sales');
    insert into ${SRC}.emp (name, dept_id, hired) values ('Ann', 1, '2026-01-02');
  `);
});

after(async () => {
  for (const a of ALIASES) await dropApp(a);
  await owner.query(`drop schema if exists ${SRC} cascade`);
  await app.close();
  await closePools();
});

const builder = async () => {
  const b = new Browser(app);
  await b.get('/builder/login');
  assert.equal((await b.submit('/builder/login', { username: 'admin', password: 'admin' })).statusCode, 303);
  return b;
};
const appOf = (alias: string) => owner.one('select * from meta.app where alias = $1', [alias]);

describe('the Create Application wizard', () => {
  test('a page type per table: the offered types fit the table; large tables get a grid', async () => {
    const b = await builder();
    const page = (await b.get(`/builder/create?schema=${SRC}`)).body;
    const options = (rel: string) => {
      const i = new RegExp(`name="t_(\\d+)" value="${rel}"`).exec(page)![1];
      return [...new RegExp(`<select id="f_k_${i}" name="k_${i}">([\\s\\S]*?)</select>`).exec(page)![1].matchAll(/value="([^"]*)"/g)].map((m) => m[1]);
    };
    assert.deepEqual(options('dept'), ['report_form', 'facets', 'cards', 'master_detail', 'grid', 'report', '']);
    assert.deepEqual(options('emp'), ['report_form', 'facets', 'cards', 'calendar', 'grid', 'report', '']);
    assert.deepEqual(options('note'), ['facets', 'cards', 'report', ''], 'no key: no form, no grid');
    assert.deepEqual(options('emp_v'), ['facets', 'cards', 'report', '']);
    // (sprint 78) the friendly name of the pages, the table's name as secondary text
    assert.match(page, new RegExp(`<label class="aw-page-kind" for="f_k_${/name="t_(\d+)" value="emp"/.exec(page)![1]}"><svg[^]*?</svg> Employees</label>`));
    assert.match(page, /<small class="muted"><code>emp<\/code> · /);
    // a very large table (the planner's estimate) is proposed as a paged grid
    await owner.query(`update pg_class set reltuples = 250000 where oid = '${SRC}.emp'::regclass`);
    try {
      const big = (await b.get(`/builder/create?schema=${SRC}`)).body;
      const i = /name="t_(\d+)" value="emp"/.exec(big)![1];
      assert.match(big, new RegExp(`name="k_${i}">[\\s\\S]*?<option value="grid" selected>`));
      assert.match(big, /about 250,000 row\(s\): a paged grid/);
    } finally {
      await owner.query(`analyze ${SRC}.emp`);
    }
  });

  test('the chosen types, features, appearance and language; then straight to the application', async () => {
    const b = await builder();
    const f = formFields(/<form method="post" action="\/builder\/apps"[\s\S]*?<\/form>/.exec((await b.get(`/builder/create?schema=${SRC}`)).body)![0]);
    const idx = (rel: string) => Object.entries(f).find(([k, v]) => k.startsWith('t_') && v === rel)![0].slice(2);
    const res = await b.submit('/builder/apps', {
      ...f, name: 'CW kinds', alias: 'cw73-kinds', authentication: 'none', description: 'People & <teams>',
      [`k_${idx('emp')}`]: 'facets', [`k_${idx('dept')}`]: 'report_form', [`k_${idx('note')}`]: '', [`k_${idx('emp_v')}`]: '',
      chart: '', f_theme: '', f_about: 'true', f_access: 'true', f_activity: 'true', f_feedback: 'true', f_pwa: 'true', base: 'lavender', nav: 'top', accent: '#aa3366', language: 'nl', icon: 'users',
    });
    assert.equal(res.statusCode, 303, res.body.slice(0, 500));
    const a = await appOf('cw73-kinds');
    assert.equal(res.headers.location, `/builder/apps/${a.id}`);
    assert.deepEqual(a.theme, { mode: 'light', base: 'lavender', nav: 'top', accent: '#aa3366', user_choice: false }, 'theme style selection was not ticked');
    assert.deepEqual([a.language, a.feedback, a.pwa, a.navbar_list], ['nl', true, true, 'NAVBAR']);
    const pages = (await owner.query(`select p.page_no, p.name, p.authz, array_agg(r.type order by r.seq) as types from meta.page p left join meta.region r on r.page_id = p.id where p.app_id = $1 group by 1, 2, 3 order by 1`, [a.id])).rows;
    assert.deepEqual(pages.map((p) => [p.page_no, p.name, p.types.join(',')]), [
      [1, 'Home', 'static,list'], [2, 'Departments', 'report'], [3, 'Department Form', 'form'], [4, 'Employees', 'facets,report'], [5, 'Employee Form', 'form'],
      [9000, 'About', 'static'], [9010, 'Activity', 'chart,report'],
    ]);
    assert.equal(pages.find((p) => p.page_no === 9010).authz, 'ADMIN');
    const hero = await owner.one(`select r.source, r.config from meta.region r join meta.page p on p.id = r.page_id where p.app_id = $1 and p.page_no = 1 and r.template = 'hero'`, [a.id]);
    assert.equal(hero.source, '<p>People &#38; &#60;teams&#62;</p>');
    assert.deepEqual(hero.config, { icon: 'users' });
    const schemes = (await owner.query(`select name, type from meta.authz_scheme where app_id = $1 order by 1`, [a.id])).rows.map((r) => `${r.name}:${r.type}`);
    assert.deepEqual(schemes, ['ADMIN:role', 'CONTRIBUTOR:sql', 'READER:sql']);
    // the Activity card is for administrators only, like its page
    assert.equal((await owner.one(`select authz from meta.list_entry where app_id = $1 and list_name = 'HOME_PAGES' and target_page = 9010`, [a.id])).authz, 'ADMIN');
  });

  test('a blank application: Home, About; a type a table can\'t have is refused', async () => {
    const b = await builder();
    const blank = formFields(/<form method="post" action="\/builder\/apps"[\s\S]*?<\/form>/.exec((await b.get('/builder/create')).body)![0]);
    assert.equal((await b.submit('/builder/apps', { ...blank, name: 'CW blank', alias: 'cw73-blank', authentication: 'none' })).statusCode, 303);
    const a = await appOf('cw73-blank');
    assert.deepEqual((await owner.query('select page_no from meta.page where app_id = $1 order by 1', [a.id])).rows.map((r) => r.page_no), [1, 9000]);
    assert.deepEqual(a.theme, { mode: 'light', base: 'iris' });
    await b.get(`/builder/create?schema=${SRC}`);
    for (const [rel, kind] of [['emp_v', 'grid'], ['note', 'report_form'], ['dept', 'calendar'], ['emp', 'nonsense']]) {
      const res = await b.submit('/builder/apps', { schema: SRC, tables: '1', features: '1', t_0: rel, k_0: kind, name: 'Bad', alias: 'cw73-bad', authentication: 'none' });
      assert.equal(res.statusCode, 422, `${rel} ${kind}`);
      assert.match(res.body, /can&#39;t have the page type/);
    }
    for (const [field, value, message] of [['language', 'xx', /Choose one of the languages/], ['icon', '"><script>', /Choose one of the icons/]] as [string, string, RegExp][]) {
      const res = await b.submit('/builder/apps', { ...blank, name: 'Bad', alias: 'cw73-bad', authentication: 'none', [field]: value });
      assert.equal(res.statusCode, 422, field);
      assert.match(res.body, message);
    }
    assert.equal((await owner.query(`select 1 from meta.app where alias = 'cw73-bad'`)).rowCount, 0);
  });
});

describe('the Create Application wizard (sprint 87, WIZ-4)', () => {
  test('row level security is shown per table before Create; the alias says it follows the name', async () => {
    await owner.query(`
      alter table ${SRC}.emp enable row level security;
      create policy emp_mine on ${SRC}.emp using (true);
      alter table ${SRC}.note enable row level security;`);
    try {
      const b = await builder();
      const page = (await b.get(`/builder/create?schema=${SRC}`)).body;
      const row = (rel: string) => new RegExp(`name="t_\\d+" value="${rel}">[\\s\\S]*?</li>`).exec(page)![0];
      assert.match(row('emp'), /<span class="tag aw-rls" title="Row level security is on \(1 policy\)[^"]*">[\s\S]*? RLS · 1<\/span>/);
      assert.match(row('note'), /<span class="tag tag-error aw-rls" title="Row level security is on without policies[^"]*">[\s\S]*?RLS, no policies<\/span>/);
      assert.doesNotMatch(row('dept'), /aw-rls/);
      // the page list and the schema's hidden fields can be swapped by the script
      assert.match(page, /<section class="region region-standard" id="aw-pages">/);
      assert.match(page, new RegExp(`<div id="aw-schema-fields"><input type="hidden" name="schema" value="${SRC}"><input type="hidden" name="tables" value="1"></div>`));
      assert.match(page, /<input id="f_alias" name="alias" value="cw73-src" required pattern="[^"]+" maxlength="50" data-derive-from="f_name">/);
      // after a refused submit the alias the developer typed stays theirs
      const res = await b.submit('/builder/apps', { name: 'X', alias: 'Not valid!', schema: SRC, features: '1' });
      assert.match(res.body, /data-derive-from="f_name" data-edited>/);
    } finally {
      await owner.query(`drop policy emp_mine on ${SRC}.emp; alter table ${SRC}.emp disable row level security; alter table ${SRC}.note disable row level security`);
    }
  });
});
