// Sprint 95 (Database Actions DA-8, part 2): the Table Properties page. Create a table from the form, preview its
// DDL, apply it in one transaction, edit it (rename, add, drop), copy it as a template, open the statements in
// the worksheet.
import { after, before, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import type { FastifyInstance } from 'fastify';
import '../src/env.ts';
import { buildApp } from '../src/app.ts';
import { closePools, owner } from '../src/db.ts';
import { Browser } from './helpers.ts';

let app: FastifyInstance;
const S = 'te95';
before(async () => {
  app = await buildApp({ logger: false });
  await owner.query(`drop schema if exists ${S} cascade; create schema ${S}; create table ${S}.dept (id int primary key, name text); insert into ${S}.dept values (1, 'Sales')`);
});
after(async () => {
  await owner.query(`drop schema if exists ${S} cascade`);
  await app.close();
  await closePools();
});
const builder = async () => {
  const b = new Browser(app);
  await b.get('/builder/login');
  assert.equal((await b.submit('/builder/login', { username: 'admin', password: 'admin' })).statusCode, 303);
  return b;
};
const NEW = {
  schema: S, name: 'emp', comment: 'People',
  'col.0.name': 'id', 'col.0.type': 'bigint', 'col.0.identity': 'by default', 'col.0.pk': 'on',
  'col.1.name': 'name', 'col.1.type': 'text', 'col.1.nn': 'on', 'col.1.comment': 'Full name',
  'col.2.name': 'dept_id', 'col.2.type': 'integer',
  'col.3.name': '', 'col.3.type': '',
  'fk.0.name': 'emp_dept_fk', 'fk.0.cols': 'dept_id', 'fk.0.ref': `${S}.dept`, 'fk.0.refcols': '', 'fk.0.del': 'set null',
  'ck.0.name': 'emp_name_ck', 'ck.0.expr': "name <> ''",
  'ix.0.name': 'emp_name_idx', 'ix.0.cols': 'lower(name)',
  rls: 'on',
};

describe('Table Properties', () => {
  test('a new table: the form, Preview DDL, Apply', async () => {
    const b = await builder();
    const form = (await b.get(`/builder/sql/objects/table?schema=${S}`)).body;
    assert.match(form, /<h1 class="u-mb1">Create table<\/h1>/);
    assert.match(form, new RegExp(`<option value="${S}" selected>`));
    assert.match(form, /name="col\.0\.name"/);
    const preview = (await b.submit('/builder/sql/objects/table', { ...NEW, mode: 'preview' })).body;
    assert.match(preview, /data-te-tab="ddl"/);
    assert.match(preview, /create table te95\.emp \(\n {2}id bigint generated by default as identity,\n {2}name text not null,\n {2}dept_id integer,\n {2}primary key \(id\),/);
    assert.match(preview, /constraint emp_dept_fk foreign key \(dept_id\) references te95\.dept on delete set null/);
    assert.match(preview, /alter table te95\.emp enable row level security;/);
    assert.equal((await owner.one(`select to_regclass('${S}.emp') as t`))!.t, null, 'a preview changes nothing');
    const applied = await b.submit('/builder/sql/objects/table', { ...NEW, mode: 'apply' });
    assert.equal(applied.statusCode, 303);
    assert.equal(applied.headers.location, `/builder/sql/objects/table?o=${S}.emp`);
    const edit = (await b.get(applied.headers.location as string)).body;
    assert.match(edit, /<h1 class="u-mb1">Table te95\.emp<\/h1>/);
    assert.match(edit, /Created te95\.emp: \d+ statements\./);
    assert.match(edit, /<input type="hidden" name="col\.1\.orig" value="name">/);
    assert.match(edit, /No changes yet/);
  });

  test('editing: rename a column, add one, drop one; a failure changes nothing', async () => {
    const b = await builder();
    await b.get(`/builder/sql/objects/table?o=${S}.emp`);
    await owner.query(`insert into ${S}.emp (name) values ('Ann')`);
    const base = { ref: `${S}.emp`, schema: S, name: 'emp', comment: 'People', rls: 'on',
      'col.0.orig': 'id', 'col.0.name': 'id', 'col.0.type': 'bigint', 'col.0.identity': 'by default', 'col.0.pk': 'on', 'col.0.nn': 'on',
      'col.1.orig': 'name', 'col.1.name': 'full_name', 'col.1.type': 'text', 'col.1.nn': 'on', 'col.1.comment': 'Full name',
      'col.2.orig': 'dept_id', 'col.2.name': 'dept_id', 'col.2.type': 'integer', 'col.2.drop': 'on',
      'col.3.orig': '', 'col.3.name': 'bonus', 'col.3.type': 'numeric(8,2)', 'col.3.def': '0',
      'ck.0.name': 'emp_name_ck', 'ck.0.expr': "(full_name <> ''::text)", 'ix.0.name': 'emp_name_idx', 'ix.0.cols': 'lower(full_name)' };
    const preview = (await b.submit('/builder/sql/objects/table', { ...base, mode: 'preview' })).body;
    assert.match(preview, /alter table te95\.emp drop constraint emp_dept_fk;/);
    assert.match(preview, /alter table te95\.emp drop column dept_id;/);
    assert.match(preview, /alter table te95\.emp rename column name to full_name;/);
    assert.match(preview, /alter table te95\.emp add column bonus numeric\(8,2\) default 0;/);
    // a NOT NULL column without a default on a table with rows fails: all of it is rolled back
    const bad = (await b.submit('/builder/sql/objects/table', { ...base, 'col.3.nn': 'on', 'col.3.def': '', mode: 'apply' })).body;
    assert.match(bad, /Nothing was changed/);
    assert.match(bad, /data-te-tab="output"/);
    assert.ok((await owner.one(`select 1 as ok from pg_attribute where attrelid = '${S}.emp'::regclass and attname = 'dept_id' and not attisdropped`)), 'dept_id is still there');
    assert.equal((await b.submit('/builder/sql/objects/table', { ...base, mode: 'apply' })).statusCode, 303);
    assert.deepEqual((await owner.query(`select attname from pg_attribute where attrelid = '${S}.emp'::regclass and attnum > 0 and not attisdropped order by attnum`)).rows.map((r) => r.attname), ['id', 'full_name', 'bonus']);
  });

  test('mistakes are listed and nothing runs; Open in the worksheet; Use as template', async () => {
    const b = await builder();
    await b.get(`/builder/sql/objects/table?schema=${S}`);
    const bad = (await b.submit('/builder/sql/objects/table', { schema: S, name: 'x y', 'col.0.name': 'a', 'col.0.type': 'text; drop table te95.dept', mode: 'apply' })).body;
    assert.match(bad, /The table needs a name/);
    assert.match(bad, /Column a: a type is a name/);
    assert.ok(await owner.one(`select to_regclass('${S}.dept') as t`));
    const ws = await b.submit('/builder/sql/objects/table', { schema: S, name: 'gadget', 'col.0.name': 'id', 'col.0.type': 'int', 'col.0.pk': 'on', mode: 'worksheet' });
    assert.equal(ws.headers.location, '/builder/sql/worksheet');
    assert.match((await b.get('/builder/sql/worksheet')).body, /create table te95\.gadget \(\n {2}id int,\n {2}primary key \(id\)\n\);<\/textarea>/);
    const tpl = (await b.get(`/builder/sql/objects/table?schema=${S}&template=${S}.emp`)).body;
    assert.match(tpl, /<h1 class="u-mb1">Create table<\/h1>/);
    assert.match(tpl, /id="te-name" name="name" value="emp_copy"/);
    assert.match(tpl, /value="emp_copy_name_idx"|value="emp_name_idx_copy"/);
    assert.match(tpl, /<input type="hidden" name="col\.0\.orig" value="">/);
  });

  test('menus and the Object Browser lead here; only tables of usable schemas', async () => {
    const b = await builder();
    const ob = (await b.get(`/builder/sql/objects?schema=${S}&k=table&o=${S}.emp`)).body;
    assert.match(ob, new RegExp(`href="/builder/sql/objects/table\\?schema=${S}&amp;o=${S}\\.emp">.*?Edit table`, 's'));
    assert.match(ob, /Edit…<\/a>/);
    assert.match(ob, /Use as template<\/a>/);
    for (const url of ['/builder/sql/objects/table?o=meta.app', `/builder/sql/objects/table?o=${S}.nope`, '/builder/sql/objects/table?template=meta.app', `/builder/sql/objects/table?o=${S}.emp_name_idx`])
      assert.equal((await b.get(url)).statusCode, 404, url);
    assert.equal((await b.submit('/builder/sql/objects/table', { schema: 'meta', name: 'evil', 'col.0.name': 'a', 'col.0.type': 'int', mode: 'apply' })).statusCode, 404);
  });
});
