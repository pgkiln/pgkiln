const regions = async (id: number, page: number) =>
  (await owner.query(`select r.* from meta.region r join meta.page p on p.id = r.page_id where p.app_id = $1 and p.page_no = $2 order by r.seq`, [id, page])).rows;
const publish = () => owner.query('update meta.page set requires_auth = false where app_id = $1', [appId]);
const flashOf = (body: string) => /class="alert[^"]*"[^>]*>([\s\S]*?)<\/div>/.exec(body)?.[1] ?? '';
/** Step 2's form for a kind, then its POST with the proposals and the overrides; returns the response. */
async function create(b: Browser, kind: string, table: string | null, page: number, over: Record<string, string | string[]> = {}) {
  const step = await b.get(`/builder/apps/${appId}/wizard?kind=${kind}${table ? `&table=${table}` : ''}`);
  assert.equal(step.statusCode, 200, `${kind}: step 2`);
  const fields = formFields(step.body);
  // checkboxes: formFields keeps the last; post every checked value of a list
  const checked = (name: string) => [...step.body.matchAll(new RegExp(`name="${name}" value="([^"]*)" checked`, 'g'))].map((m) => m[1]);
  const lists: Record<string, string[]> = {};
  for (const n of ['columns', 'facets', 'configs', 'tables']) if (checked(n).length) lists[n] = checked(n);
  const res = await b.submit(`/builder/apps/${appId}/wizard`, { ...fields, ...lists, report_page: String(page), ...over });
  assert.equal(res.statusCode, 303, `${kind}: created`);
  return res;
}

