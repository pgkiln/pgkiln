// Sprint 95 (Database Actions DA-8, part 2): a table as a definition (src/tabledef.ts). Round trips against the
// database: CREATE from a definition, read it back, change it, apply the ALTER statements, read again.
import { after, before, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import '../src/env.ts';
import { closePools, owner } from '../src/db.ts';
import { checkTable, emptyTable, readTable, tableSql, type TableDef } from '../src/tabledef.ts';

const S = 'td95';
before(async () => {
  await owner.query(`drop schema if exists ${S} cascade; create schema ${S}; create table ${S}.dept (id int primary key, name text)`);
});
after(async () => {
  await owner.query(`drop schema if exists ${S} cascade`);
  await closePools();
});
const apply = async (sql: string[]) => {
  await owner.query('begin');
  try {
    for (const x of sql) await owner.query(x);
    await owner.query('commit');
  } catch (e) {
    await owner.query('rollback');
    throw e;
  }
};
const col = (name: string, type: string, extra: Partial<TableDef['columns'][number]> = {}) =>
  ({ name, orig: '', type, notNull: false, default: '', identity: '' as const, generated: '', comment: '', pk: false, ...extra });

describe('table definitions', () => {
  test('a new table: CREATE with keys, checks, foreign keys, indexes, comments and row level security', async () => {
    const def: TableDef = {
      ...emptyTable(S),
      name: 'emp',
      comment: 'People',
      columns: [
        col('id', 'bigint', { identity: 'by default', pk: true }),
        col('name', 'text', { notNull: true, comment: 'Full name' }),
        col('email', 'varchar(200)'),
        col('salary', 'numeric(9,2)', { default: '0' }),
        col('dept_id', 'integer'),
      ],
      pkName: 'emp_pk',
      uniques: [{ name: 'emp_email_uk', columns: 'email' }],
      checks: [{ name: 'emp_salary_ck', expr: 'salary >= 0' }],
      fks: [{ name: 'emp_dept_fk', columns: 'dept_id', refTable: `${S}.dept`, refColumns: 'id', onDelete: 'set null' }],
      indexes: [{ name: 'emp_name_idx', columns: 'lower(name)', unique: false }],
      rls: true,
    };
    assert.deepEqual(checkTable(def, null), []);
    const sql = tableSql(def, null);
    assert.match(sql[0], /^create table td95\.emp \(\n {2}id bigint generated by default as identity,\n {2}name text not null,/);
    assert.match(sql[0], /constraint emp_dept_fk foreign key \(dept_id\) references td95\.dept \(id\) on delete set null\n\);$/);
    await apply(sql);
    const back = (await readTable(owner, `${S}.emp`))!;
    assert.deepEqual(back.columns.map((c) => [c.name, c.type, c.notNull, c.default, c.identity, c.pk, c.comment]), [
      ['id', 'bigint', true, '', 'by default', true, ''], ['name', 'text', true, '', '', false, 'Full name'], ['email', 'character varying(200)', false, '', '', false, ''],
      ['salary', 'numeric(9,2)', false, '0', '', false, ''], ['dept_id', 'integer', false, '', '', false, ''],
    ]);
    assert.equal(back.pkName, 'emp_pk');
    assert.deepEqual(back.indexes, [{ name: 'emp_name_idx', columns: 'lower(name)', unique: false }]);
    assert.deepEqual(back.checks, [{ name: 'emp_salary_ck', expr: '(salary >= (0)::numeric)' }]);
    assert.equal(back.rls, true);
    assert.equal(back.comment, 'People');
    // read back and unchanged: nothing to do
    assert.deepEqual(tableSql(back, back), []);
  });

  test('changes become ALTER statements in a working order', async () => {
    const old = (await readTable(owner, `${S}.emp`))!;
    const def: TableDef = structuredClone(old);
    def.name = 'employee';
    def.columns = def.columns.filter((c) => c.name !== 'email');
    def.columns.find((c) => c.name === 'name')!.name = 'full_name';
    def.columns.find((c) => c.name === 'salary')!.type = 'numeric(12,2)';
    def.columns.find((c) => c.name === 'salary')!.default = '';
    def.columns.push(col('bonus', 'numeric(8,2)', { comment: 'Yearly' }));
    def.uniques = [];
    def.checks[0].expr = 'salary >= 0 and salary < 1000000';
    def.fks[0].onDelete = 'cascade';
    def.indexes.push({ name: 'employee_bonus_idx', columns: 'bonus', unique: false });
    def.rls = false;
    def.comment = '';
    const sql = tableSql(def, old);
    assert.deepEqual(sql.slice(0, 2), ['alter table td95.emp rename to employee;', 'alter table td95.employee drop constraint emp_email_uk;']);
    assert.ok(sql.includes('alter table td95.employee drop column email;'));
    assert.ok(sql.includes('alter table td95.employee rename column name to full_name;'));
    assert.ok(sql.includes('alter table td95.employee\n  alter column salary type numeric(12,2) using salary::numeric(12,2),\n  alter column salary drop default;'));
    assert.ok(sql.includes("comment on column td95.employee.bonus is 'Yearly';"));
    assert.equal(sql[sql.length - 1], 'alter table td95.employee disable row level security;');
    await apply(sql);
    const back = (await readTable(owner, `${S}.employee`))!;
    assert.deepEqual(back.columns.map((c) => c.name), ['id', 'full_name', 'salary', 'dept_id', 'bonus']);
    assert.equal(back.fks[0].onDelete, 'cascade');
    assert.deepEqual(back.uniques, []);
    assert.equal(back.indexes.length, 2);
    assert.deepEqual(tableSql(back, back), []);
  });

  test('the primary key moves; mistakes are reported before any SQL', async () => {
    const old = (await readTable(owner, `${S}.employee`))!;
    const def: TableDef = structuredClone(old);
    for (const c of def.columns) c.pk = c.name === 'full_name';
    await apply(tableSql(def, old));
    const back = (await readTable(owner, `${S}.employee`))!;
    assert.deepEqual(back.columns.filter((c) => c.pk).map((c) => c.name), ['full_name']);
    assert.equal(back.pkName, 'emp_pk');
    const bad: TableDef = { ...emptyTable(S), name: '1x', columns: [col('a', 'text; drop table x'), col('a', 'int', { default: '1; select 2' })], checks: [{ name: 'c', expr: '' }] };
    const errors = checkTable(bad, null);
    assert.ok(errors.some((e) => /table needs a name/.test(e)));
    assert.ok(errors.some((e) => /Column a: a type is/.test(e)));
    assert.ok(errors.some((e) => /Column a is there twice/.test(e)));
    assert.ok(errors.some((e) => /a default is one expression/.test(e)));
    assert.ok(errors.some((e) => /Check c: a name and one expression/.test(e)));
    assert.equal(await readTable(owner, `${S}.nope`), null);
  });
});

