// Sprint 100 (Database Actions DA-11, part 1): SQL Workshop › RESTful Services, AutoREST. A table or view is
// published through an application (meta.rest_object) and served at /a/<alias>/autorest/<object>/ as the
// application's database role, with the application's tokens.
import { after, before, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import type { FastifyInstance } from 'fastify';
import '../src/env.ts';
import { buildApp } from '../src/app.ts';
import { issueApiToken } from '../src/api.ts';
import { closePools, owner } from '../src/db.ts';
import { orderBy, splitKey, type Column } from '../src/runtime/autorest.ts';
import { Browser } from './helpers.ts';

let app: FastifyInstance;
let appId: number;
const S = 'ar100';
const token: Record<string, string> = {};

before(async () => {
  app = await buildApp({ logger: false });
  appId = (await owner.one(`select id from meta.app where alias = 'hr'`)).id;
  for (const u of ['king', 'allen']) token[u] = (await issueApiToken(appId, u, 1)).token;
  await owner.query(`delete from meta.rest_object where app_id = $1`, [appId]);
  await owner.query(`drop schema if exists ${S} cascade`);
  await owner.query(`
    create schema ${S};
    grant usage on schema ${S} to hr_app;
    create table ${S}.note (id int generated by default as identity primary key, owner text not null default meta.app_user(), body text, secret text, made date default current_date);
    grant select (id, owner, body, made), insert (owner, body), update (body), delete on ${S}.note to hr_app;
    alter table ${S}.note enable row level security;
    create policy mine on ${S}.note using (owner = meta.app_user() or meta.has_role('admin'));
    insert into ${S}.note (owner, body, secret) values ('allen', 'allen''s first', 's1'), ('allen', 'allen''s second', 's2'), ('king', 'king''s 50%_note', 's3');
    create table ${S}.pair (a int, b text, v text, primary key (a, b));
    grant select, insert, update, delete on ${S}.pair to hr_app;
    insert into ${S}.pair values (1, 'x', 'one-x'), (1, 'y', 'one-y');
    create view ${S}.note_v with (security_invoker = true) as select id, body from ${S}.note;
    grant select on ${S}.note_v to hr_app;
    create table ${S}.mine (id int primary key);
    alter table ${S}.mine owner to hr_app;
  `);
});

after(async () => {
  await owner.query(`delete from meta.rest_object where app_id = $1`, [appId]);
  await owner.query(`drop schema if exists ${S} cascade`);
  await app.close();
  await closePools();
});

const builder = async () => {
  const b = new Browser(app);
  await b.get('/builder/login');
  assert.equal((await b.submit('/builder/login', { username: 'admin', password: 'admin' })).statusCode, 303);
  return b;
};
const call = (method: string, path: string, who?: string, payload?: unknown) =>
  app.inject({
    method: method as 'GET',
    url: `/a/hr/autorest/${path}`,
    headers: { ...(who ? { authorization: `Bearer ${token[who] ?? who}` } : {}), ...(payload !== undefined ? { 'content-type': 'application/json' } : {}) },
    payload: payload !== undefined ? JSON.stringify(payload) : undefined,
  });
const publish = (schema: string, name: string, extra: Record<string, unknown> = {}) =>
  owner.one(`insert into meta.rest_object (app_id, schema_name, object_name, alias, methods, auth, roles) values ($1, $2, $3, $4, $5, $6, $7) returning id`,
    [appId, schema, name, extra.alias ?? name, extra.methods ?? ['GET', 'POST', 'PUT', 'DELETE'], extra.auth ?? 'token', extra.roles ?? []]);

describe('helpers', () => {
  test('keys split per column; order names readable columns only', () => {
    assert.deepEqual(splitKey('1', 1), ['1']);
    assert.deepEqual(splitKey('1,a%2Cb', 2), ['1', 'a,b']);
    assert.equal(splitKey('1,2', 1), null);
    assert.equal(splitKey('a/b', 1), null);
    assert.equal(splitKey('%E0%A4%A', 1), null);
    const cols: Column[] = [{ name: 'id', type: 'integer', cat: 'N', readable: true, pk: 1 }, { name: 'Name', type: 'text', cat: 'S', readable: true, pk: null }, { name: 'secret', type: 'text', cat: 'S', readable: false, pk: null }];
    assert.equal(orderBy(undefined, cols), 't."id"');
    assert.equal(orderBy('Name.desc,id', cols), 't."Name" desc, t."id"');
    assert.equal(orderBy('secret', cols), null);
    assert.equal(orderBy('id;drop table x', cols), null);
  });
});

describe('REST › Enable on hr.dept', () => {
  test('the object menu leads to the Enable form; enabling shows the URL, cURL, fetch and OpenAPI', async () => {
    const b = await builder();
    const ws = (await b.get('/builder/sql/worksheet?schema=hr')).body;
    assert.match(ws, /href="\/builder\/sql\/rest\/object\?schema=hr&amp;name=dept"[^>]*>.*REST › Enable \/ Disable/);
    const go = await b.get('/builder/sql/rest/object?schema=hr&name=dept');
    assert.equal(go.statusCode, 302);
    assert.equal(go.headers.location, '/builder/sql/rest?schema=hr&name=dept#enable');
    const form = (await b.get('/builder/sql/rest?schema=hr&name=dept')).body;
    assert.match(form, /<option value="\[&quot;hr&quot;,&quot;dept&quot;\]" selected>hr\.dept<\/option>/);
    assert.match(form, /runs as hr_app/);
    const res = await b.submit('/builder/sql/rest', { object: '["hr","dept"]', app_id: String(appId), alias: '', methods: ['GET'], auth: 'token', page_size: '2', roles: '' });
    assert.equal(res.statusCode, 303);
    const id = Number(/\/builder\/sql\/rest\/(\d+)$/.exec(String(res.headers.location))![1]);
    const page = (await b.get(`/builder/sql/rest/${id}`)).body;
    assert.match(page, /\/a\/hr\/autorest\/dept\//);
    assert.match(page, /curl &quot;http:\/\/[^"]*\/a\/hr\/autorest\/dept\/\?limit=10&amp;q=a&quot; -H &quot;Authorization: Bearer \$TOKEN&quot;/);
    assert.match(page, /const res = await fetch\(/);
    assert.match(page, /\/a\/hr\/autorest\/openapi\.json/);
    assert.match(page, /✓ Runs as <code>hr_app<\/code>/);
    assert.match(page, /Primary key deptno/);
    // the menu now leads to its page
    assert.equal((await b.get('/builder/sql/rest/object?schema=hr&name=dept')).headers.location, `/builder/sql/rest/${id}`);
    assert.match((await b.get('/builder/sql/rest')).body, /<a href="\/builder\/sql\/rest\/\d+">hr\.dept<\/a>/);
    assert.match((await b.get('/builder/sql')).body, /RESTful Services/, 'on the Launchpad');

    // the endpoint: JSON with paging; without a token 401
    const r = await call('GET', 'dept/', 'king');
    assert.equal(r.statusCode, 200);
    const j = r.json();
    assert.deepEqual(Object.keys(j), ['items', 'offset', 'limit', 'has_more']);
    assert.equal(j.limit, 2);
    assert.equal(j.items.length, 2);
    assert.equal(j.has_more, true);
    assert.deepEqual(Object.keys(j.items[0]), ['deptno', 'dname', 'loc', 'lat', 'lng']);
    const p2 = (await call('GET', 'dept/?limit=3&offset=2', 'king')).json();
    assert.equal(p2.offset, 2);
    assert.equal(p2.items.length, 2);
    assert.equal(p2.has_more, false);
    assert.equal((await call('GET', 'dept/')).statusCode, 401);
    assert.equal((await call('GET', 'dept/', 'not-a-token')).statusCode, 401);
    assert.equal((await call('GET', `dept/${j.items[0].deptno}`, 'king')).json().dname, j.items[0].dname);
    assert.equal((await call('POST', 'dept/', 'king', { dname: 'x' })).statusCode, 405, 'GET only');

    // roles: allen has none of them
    await b.submit(`/builder/sql/rest/${id}`, { methods: ['GET'], auth: 'token', page_size: '2', roles: 'manager', enabled: '1' });
    assert.equal((await call('GET', 'dept/', 'allen')).statusCode, 403);
    assert.equal((await call('GET', 'dept/', 'king')).statusCode, 200);
    // disabled: 404; removed: 404
    await b.submit(`/builder/sql/rest/${id}`, { methods: ['GET'], auth: 'token', page_size: '2', roles: '', enabled: '0' });
    assert.equal((await call('GET', 'dept/', 'king')).statusCode, 404);
    assert.equal((await b.submit(`/builder/sql/rest/${id}/delete`, {})).statusCode, 303);
    assert.equal((await owner.one('select count(*)::int as n from meta.rest_object where id = $1', [id])).n, 0);
  });

  test('the Enable form refuses what does not work', async () => {
    const b = await builder();
    await b.get('/builder/sql/rest');
    const post = (form: Record<string, string | string[]>) => b.submit('/builder/sql/rest', { app_id: String(appId), auth: 'token', page_size: '25', methods: ['GET'], ...form });
    assert.match((await post({ object: '["hr","nope"]' })).body, /Choose a table or view/);
    assert.match((await post({ object: '["meta","app"]' })).body, /Choose a table or view/);
    assert.match((await post({ object: `["${S}","mine"]` })).body, /owns ar100\.mine/);
    assert.match((await post({ object: `["${S}","note_v"]`, methods: ['GET', 'PUT'] })).body, /PUT and DELETE need a primary key/);
    assert.match((await post({ object: `["${S}","note"]`, alias: 'Bad Name' })).body, /The URL name starts/);
    assert.match((await post({ object: `["${S}","note"]`, methods: [] })).body, /at least one method/);
    assert.match((await post({ object: `["${S}","note"]`, auth: '' })).body, /Choose who may call it/);
    assert.equal((await post({ object: `["${S}","note"]` })).statusCode, 303);
    assert.match((await post({ object: `["${S}","note"]`, alias: 'note2' })).body, /already publishes ar100\.note/);
    assert.match((await post({ object: `["${S}","pair"]`, alias: 'note' })).body, /already publishes something as note/);
    await owner.query(`delete from meta.rest_object where app_id = $1`, [appId]);
  });
});

describe('the endpoints', () => {
  before(async () => {
    await publish(S, 'note');
    await publish(S, 'pair');
    await publish(S, 'note_v', { methods: ['GET'], auth: 'public', alias: 'notes-public' });
  });

  test('row level security and column grants apply; filters, search and order', async () => {
    const allen = (await call('GET', 'note/', 'allen')).json();
    assert.deepEqual(allen.items.map((r: any) => r.body), ['allen\'s first', 'allen\'s second']);
    assert.ok(!('secret' in allen.items[0]), 'a column the role may not select is left out');
    assert.equal((await call('GET', 'note/', 'king')).json().items.length, 3, 'admin sees all (policy)');
    assert.deepEqual((await call('GET', 'note/?owner=king', 'king')).json().items.map((r: any) => r.body), ['king\'s 50%_note']);
    assert.deepEqual((await call('GET', 'note/?q=second', 'king')).json().items.map((r: any) => r.body), ['allen\'s second']);
    assert.equal((await call('GET', 'note/?q=%25', 'king')).json().items.length, 1, '% is literal');
    assert.equal((await call('GET', 'note/?q=_', 'king')).json().items.length, 1, '_ is literal');
    assert.deepEqual((await call('GET', 'note/?order=id.desc&limit=1', 'king')).json().items.map((r: any) => r.body), ['king\'s 50%_note']);
    const king = (await call('GET', 'note/?owner=king', 'king')).json().items[0];
    assert.equal((await call('GET', `note/${king.id}`, 'allen')).statusCode, 404, 'hidden by RLS');
    assert.equal((await call('GET', 'note/?secret=s1', 'king')).statusCode, 400);
    assert.equal((await call('GET', 'note/?order=secret', 'king')).statusCode, 400);
    assert.equal((await call('GET', 'note/?limit=abc', 'king')).statusCode, 400);
    assert.equal((await call('GET', 'note/?id=abc', 'king')).statusCode, 400, 'invalid input');
    assert.equal((await call('GET', 'note/?limit=100000', 'king')).json().limit, 500);
  });

  test('POST, PUT and DELETE as the caller', async () => {
    const made = await call('POST', 'note/', 'allen', { body: 'from REST' });
    assert.equal(made.statusCode, 201);
    const row = made.json();
    assert.equal(row.owner, 'allen');
    assert.equal(row.body, 'from REST');
    assert.equal(made.headers.location, `/a/hr/autorest/note/${row.id}`);
    assert.equal((await call('POST', 'note/', 'allen', { body: 'x', secret: 'y' })).statusCode, 403, 'no insert grant on secret');
    assert.equal((await call('POST', 'note/', 'allen', { nope: 1 })).statusCode, 400);
    assert.equal((await call('POST', 'note/', 'allen', [{ body: 'x' }])).statusCode, 400);
    assert.equal((await call('POST', 'note/', 'allen', { owner: 'king', body: 'forged' })).statusCode, 403, 'RLS with check');
    const put = await call('PUT', `note/${row.id}`, 'allen', { body: 'changed' });
    assert.equal(put.statusCode, 200);
    assert.equal(put.json().body, 'changed');
    assert.equal((await call('PUT', `note/${row.id}`, 'allen', { owner: 'king' })).statusCode, 403, 'no update grant on owner');
    assert.equal((await call('PUT', `note/${row.id}`, 'allen', {})).statusCode, 400);
    const kings = (await call('GET', 'note/?owner=king', 'king')).json().items[0];
    assert.equal((await call('PUT', `note/${kings.id}`, 'allen', { body: 'hijack' })).statusCode, 404);
    assert.equal((await call('DELETE', `note/${kings.id}`, 'allen')).statusCode, 404);
    assert.equal((await call('DELETE', `note/${row.id}`, 'allen')).statusCode, 204);
    assert.equal((await call('GET', `note/${row.id}`, 'allen')).statusCode, 404);
    assert.equal((await call('PUT', 'note/', 'allen', { body: 'x' })).statusCode, 405);
    assert.equal((await call('POST', `note/${kings.id}`, 'allen', { body: 'x' })).statusCode, 405);
  });

  test('composite keys; views; public objects', async () => {
    assert.equal((await call('GET', 'pair/1,y', 'king')).json().v, 'one-y');
    assert.equal((await call('GET', 'pair/1', 'king')).statusCode, 404);
    assert.equal((await call('PUT', 'pair/1,x', 'king', { v: 'changed' })).json().v, 'changed');
    const pub = await call('GET', 'notes-public/');
    assert.equal(pub.statusCode, 200, 'public: no token');
    assert.equal(pub.json().items.length, 0, 'as nobody, RLS hides every note');
    assert.equal((await call('GET', 'notes-public/', 'king')).json().items.length, 3);
    assert.equal((await call('GET', 'notes-public/1', 'king')).statusCode, 404, 'no primary key: no single rows');
  });

  test('OpenAPI: public objects without a token, all with one', async () => {
    const anon = (await app.inject({ url: '/a/hr/autorest/openapi.json' })).json();
    assert.equal(anon.openapi, '3.0.3');
    assert.deepEqual(Object.keys(anon.paths), ['/notes-public/']);
    const all = (await app.inject({ url: '/a/hr/autorest/openapi.json', headers: { authorization: `Bearer ${token.king}` } })).json();
    assert.deepEqual(Object.keys(all.paths).sort(), ['/note/', '/note/{key}', '/notes-public/', '/pair/', '/pair/{key}']);
    assert.ok(!('secret' in all.components.schemas.note.properties));
    assert.equal(all.components.schemas.note.properties.id.type, 'integer');
    assert.equal((await app.inject({ url: '/a/hr/autorest/openapi.json', headers: { authorization: 'Bearer nope' } })).statusCode, 401);
    assert.equal((await app.inject({ url: '/a/nope/autorest/openapi.json' })).statusCode, 404);
  });
});
