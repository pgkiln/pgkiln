// Sprint 78: generated reports and grids read the same (migration 100; parity
// handoff GEN-2, GEN-1, GEN-7): one column per foreign key in a faceted
// search report (the key hidden), friendly headings and number formats in
// interactive grids and master-detail pages, no two visible columns of a
// generated report or grid with the same heading.
import { after, before, describe, test } from 'node:test';
import assert from 'node:assert/strict';
import type { FastifyInstance } from 'fastify';
import '../src/env.ts';
import { buildApp } from '../src/app.ts';
import { closePools, owner } from '../src/db.ts';
import { Browser } from './helpers.ts';

let app: FastifyInstance;
let appId: number;
const alias = 'gen-s78';
const ROLE = 'pgkiln_s78_gen';
const SCHEMA = 'gen78';

before(async () => {
  app = await buildApp({ logger: false });
  await owner.query(`delete from meta.app where alias = $1`, [alias]);
  await owner.query(`drop schema if exists ${SCHEMA} cascade`);
  await owner.query(`drop owned by ${ROLE}`).catch(() => undefined);
  await owner.query(`drop role if exists ${ROLE}`);
  await owner.query(`create role ${ROLE} nologin`);
  await owner.query(`grant ${ROLE} to pgkiln_runtime`);
  await owner.query(`create schema ${SCHEMA}`);
  await owner.query(`
    create table ${SCHEMA}.dept (deptno int primary key, dname text not null, loc text, lat numeric(9,5), lng numeric(9,5));
    create table ${SCHEMA}.emp (
      empno int generated by default as identity primary key, ename text not null, job text,
      mgr int references ${SCHEMA}.emp, hiredate date, sal numeric(9,2), comm numeric(9,2),
      deptno int references ${SCHEMA}.dept);
    insert into ${SCHEMA}.dept values (10, 'ACCOUNTING', 'NEW YORK', 40.7128, -74.006), (30, 'SALES', 'CHICAGO', 41.8781, -87.6298);
    insert into ${SCHEMA}.emp (empno, ename, job, mgr, sal, deptno) overriding system value values
      (1, 'KING', 'PRESIDENT', null, 5000, 10), (2, 'BLAKE', 'MANAGER', 1, 2850, 30), (3, 'ALLEN', 'SALESMAN', 2, 1600, 30);
    grant usage on schema ${SCHEMA} to ${ROLE};
    grant select, insert, update, delete on all tables in schema ${SCHEMA} to ${ROLE};
    grant usage on all sequences in schema ${SCHEMA} to ${ROLE};
  `);
  appId = (await owner.one(`insert into meta.app (alias, name, authentication, db_role) values ($1, 'Generated', 'none', $2) returning id`, [alias, ROLE])).id;
  await owner.query(`insert into meta.page (app_id, page_no, name, requires_auth) values ($1, 1, 'Home', false)`, [appId]);
  const gen = (kind: string, table: string, page: number, options: object = {}) =>
    owner.query('select meta.generate_page($1, $2, $3::regclass, $4, $5)', [alias, kind, `${SCHEMA}.${table}`, page, JSON.stringify(options)]);
  await gen('facets', 'emp', 2, { form_page: 3 });
  await gen('report_form', 'emp', 4, { form_page: 5 });
  await gen('master_detail', 'dept', 6);
  await gen('grid', 'dept', 7);
  await gen('map', 'dept', 8);
  await owner.query(`update meta.page set requires_auth = false where app_id = $1`, [appId]);
});

after(async () => {
  await owner.query('delete from meta.app where id = $1', [appId]);
  await owner.query(`drop schema if exists ${SCHEMA} cascade`);
  await owner.query(`drop owned by ${ROLE}`);
  await owner.query(`drop role if exists ${ROLE}`);
  await app.close();
  await closePools();
});

const regions = async (page: number) =>
  (
    await owner.query(
      `select r.* from meta.region r join meta.page p on p.id = r.page_id where p.app_id = $1 and p.page_no = $2 and r.type in ('report', 'grid') order by r.seq`,
      [appId, page],
    )
  ).rows;

/** The columns a report or grid shows, with their headings (a master's item as the detail's bind). */
const shown = async (r: { source: string; config: any }) => {
  const sql = r.source.replace(/:(P\d+_\w+)::(\w+)/g, 'null::$2');
  const res = await owner.query(`select * from (${sql}) x limit 0`);
  const hidden = new Set<string>(r.config.hidden ?? []);
  return res.fields.map((f) => f.name).filter((n) => !hidden.has(n)).map((n) => [n, r.config.headings?.[n]] as const);
};

describe('generated reports and grids (sprint 78)', () => {
  test('a faceted search report: one column per foreign key, the key hidden but kept for filters and links', async () => {
    const [rep] = await regions(2);
    assert.deepEqual(rep.config.hidden, ['mgr', 'deptno']);
    assert.match(rep.source, /t\.mgr,/, 'the key stays in the query');
    const cols = await shown(rep);
    assert.deepEqual(cols.filter(([, h]) => h === 'Manager').map(([n]) => n), ['mgr_ename']);
    assert.deepEqual(cols.filter(([, h]) => h === 'Department').map(([n]) => n), ['deptno_dname']);
    assert.deepEqual(rep.config.formats, { sal: '999G999G999G990D00', comm: '999G999G999G990D00' });
    // the facets filter on the display column
    const facets = (await owner.one(`select config from meta.region r join meta.page p on p.id = r.page_id where p.app_id = $1 and p.page_no = 2 and r.type = 'facets'`, [appId])).config.facets;
    assert.deepEqual(facets.map((f: { column: string }) => f.column).filter((c: string) => /mgr|deptno/.test(c)), ['mgr_ename', 'deptno_dname']);
  });

  test('no two visible columns of a generated report or grid share a heading; every column has one', async () => {
    for (const page of [2, 4, 6, 7, 8]) {
      const rs = await regions(page);
      assert.ok(rs.length, `page ${page} has a report or grid`);
      for (const r of rs) {
        const cols = await shown(r);
        const heads = cols.map(([n, h]) => h ?? n);
        assert.deepEqual(heads.filter((h, i) => heads.indexOf(h) !== i), [], `page ${page} ${r.title}: ${heads.join(', ')}`);
        if (r.type === 'grid') assert.deepEqual(cols.filter(([, h]) => !h).map(([n]) => n), [], `page ${page} ${r.title}: a heading per column`);
      }
    }
  });

  test('grids: friendly headings and number formats (the grid page and both grids of a master-detail page)', async () => {
    const [master, detail] = await regions(6);
    assert.deepEqual(master.config.headings, { deptno: 'Department Number', dname: 'Name', loc: 'Location', lat: 'Latitude', lng: 'Longitude' });
    assert.equal(master.config.formats.lat, '999G999G999G990D00000');
    assert.equal(detail.config.headings.hiredate, 'Hire Date');
    assert.equal(detail.config.headings.sal, 'Salary');
    assert.equal(detail.config.formats.sal, '999G999G999G990D00');
    assert.equal(detail.config.formats.empno, undefined, 'keys get no mask');
    const [grid] = await regions(7);
    assert.equal(grid.config.headings.deptno, 'Department Number');
    assert.ok(grid.config.columns, 'the grid keeps its column settings');
    const [, list] = [null, ...(await regions(8))];
    assert.equal(list.config.formats.lat, '999G999G999G990D00000', 'the map\'s list report');
  });

  test('the faceted search page: one Manager heading, the parent\'s name, a formatted salary', async () => {
    const body = (await new Browser(app).get(`/a/${alias}/2`)).body;
    const heads = [...body.matchAll(/<th[^>]*>(?:<[^>]+>)*([^<]+)/g)].map((m) => m[1].trim());
    assert.equal(heads.filter((h) => h === 'Manager').length, 1, heads.join(' | '));
    assert.equal(heads.filter((h) => h === 'Department').length, 1, heads.join(' | '));
    assert.match(body, /data-label="Manager">KING</);
    assert.match(body, /2,850\.00/);
    assert.doesNotMatch(body, /data-label="Manager">1</);
  });

  test('the master-detail page: the grids carry the friendly headings', async () => {
    const body = (await new Browser(app).get(`/a/${alias}/6`)).body;
    assert.match(body, /data-label="Department Number"/);
    assert.match(body, /data-label="Latitude"/);
    assert.doesNotMatch(body, /data-label="Deptno"/);
  });
});
