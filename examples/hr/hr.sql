-- The employee record of the signed-in application user.
create function hr.current_empno() returns int
language sql stable as $$
  select empno from hr.emp where lower(username) = lower(meta.app_user())
$$;

-- Is the signed-in user somewhere above p_empno in the management chain?
create function hr.is_manager_of(p_empno int) returns boolean
language sql stable as $$
  with recursive chain (empno, mgr) as (
    select empno, mgr from hr.emp where empno = p_empno
    union all
    select e.empno, e.mgr from hr.emp e join chain c on e.empno = c.mgr
  ) cycle empno set is_cycle using path
  select exists (select 1 from chain where empno <> p_empno and empno = hr.current_empno())
$$;

create function hr.business_days(p_from date, p_to date) returns int
language sql immutable as $$
  select count(*)::int
    from generate_series(p_from, p_to, interval '1 day') d
   where extract(isodow from d) < 6
$$;

-- Used by a dynamic action: typical salary for a job.
create function hr.suggest_salary(p_job text) returns numeric
language sql stable as $$
  select round(avg(sal), -1) from hr.emp where job = upper(p_job)
$$;

