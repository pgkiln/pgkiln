-- Button "Give 10% raise" (page 3).
create function hr.give_raise(p_empno int, p_pct numeric) returns numeric
language plpgsql as $$
declare
  v_sal numeric;
begin
  if not (meta.has_role('manager') or meta.has_role('admin')) then
    raise exception 'Only managers can give raises.';
  end if;
  if p_pct <= 0 or p_pct > 20 then
    raise exception 'A raise must be between 0 and 20 percent.';
  end if;
  if p_empno = hr.current_empno() then
    raise exception 'You cannot give yourself a raise.';
  end if;
  update hr.emp set sal = round(sal * (1 + p_pct / 100), 2)
   where empno = p_empno
  returning sal into v_sal;
  if not found then
    raise exception 'Employee % not found.', p_empno;
  end if;
  return v_sal;
end
$$;

-- Button "Submit request" (page 7).
create function hr.request_leave(p_start date, p_end date, p_reason text) returns int
language plpgsql as $$
declare
  v_empno int := hr.current_empno();
  v_days  int;
  v_used  int;
  v_id    int;
begin
  if v_empno is null then
    raise exception 'Your account is not linked to an employee, so you cannot request leave.';
  end if;
  if p_start < current_date then
    raise exception 'Leave cannot start in the past.' using column = 'start_date';
  end if;
  if p_end < p_start then
    raise exception 'The end date must be on or after the start date.' using column = 'end_date';
  end if;
  v_days := hr.business_days(p_start, p_end);
  if v_days = 0 then
    raise exception 'The selected period contains no working days.' using column = 'end_date';
  end if;
  if exists (select 1 from hr.leave_request
              where empno = v_empno and status in ('PENDING', 'APPROVED')
                and daterange(start_date, end_date, '[]') && daterange(p_start, p_end, '[]')) then
    raise exception 'This period overlaps with another leave request.';
  end if;
  select coalesce(sum(days), 0) into v_used
    from hr.leave_request
   where empno = v_empno and status = 'APPROVED'
     and extract(year from start_date) = extract(year from p_start);
  if v_used + v_days > 25 then
    raise exception 'Not enough leave left: % of 25 days used this year, % requested.', v_used, v_days;
  end if;

  insert into hr.leave_request (empno, start_date, end_date, days, reason)
  values (v_empno, p_start, p_end, v_days, p_reason)
  returning id into v_id;
  return v_id;
end
$$;

-- Buttons "Approve" / "Reject" (page 7).
create function hr.decide_leave(p_id int, p_decision text, p_note text default null) returns void
language plpgsql as $$
declare
  r hr.leave_request;
begin
  if p_decision not in ('APPROVED', 'REJECTED') then
    raise exception 'Invalid decision %.', p_decision;
  end if;
  select * into r from hr.leave_request where id = p_id for update;
  if not found then
    raise exception 'Leave request % not found.', p_id;
  end if;
  if r.status <> 'PENDING' then
    raise exception 'This request has already been %.', lower(r.status);
  end if;
  if r.empno = hr.current_empno() then
    raise exception 'You cannot decide on your own leave request.';
  end if;
  if not (hr.is_manager_of(r.empno) or meta.has_role('admin')) then
    raise exception 'Only a manager of this employee can decide on the request.';
  end if;
  update hr.leave_request
     set status = p_decision, decided_by = meta.app_user(), decided_at = now(), decision_note = p_note
   where id = p_id;
end
$$;

-- Button "Withdraw" (page 7).
create function hr.withdraw_leave(p_id int) returns void
language plpgsql as $$
begin
  update hr.leave_request set status = 'WITHDRAWN'
   where id = p_id and status = 'PENDING' and empno = hr.current_empno();
  if not found then
    raise exception 'Only your own pending requests can be withdrawn.';
  end if;
end
$$;

