-- Generic audit trail. meta.app_user() carries the application user into
-- the database session, so triggers know WHO made the change, not just
-- which database role. For updates only changed columns are stored.
create function hr.audit() returns trigger
language plpgsql security definer set search_path = hr, pg_catalog as $$
declare
  v_old jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  v_new jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
  v_pk  text  := coalesce(v_new, v_old) ->> tg_argv[0];
begin
  if tg_op = 'UPDATE' then
    select jsonb_object_agg(n.key, n.value) into v_new
      from jsonb_each(to_jsonb(new)) n
     where n.value is distinct from v_old -> n.key;
    if v_new is null then
      return new;  -- nothing changed
    end if;
    select jsonb_object_agg(o.key, o.value) into v_old
      from jsonb_each(to_jsonb(old)) o
     where v_new ? o.key;
  end if;
  insert into hr.audit_log (table_name, row_pk, action, changed_by, old_values, new_values)
  values (tg_table_name, v_pk, tg_op, meta.app_user(), v_old, v_new);
  return coalesce(new, old);
end
$$;

create trigger emp_audit after insert or update or delete on hr.emp
  for each row execute function hr.audit('empno');
create trigger dept_audit after insert or update or delete on hr.dept
  for each row execute function hr.audit('deptno');
create trigger leave_audit after insert or update or delete on hr.leave_request
  for each row execute function hr.audit('id');

-- A business rule enforced in the database. "using column" tells the
-- runtime which form field to attach the message to (the item whose
-- source column is sal), just like a validation.
create function hr.check_salary() returns trigger
language plpgsql as $$
declare
  v_max numeric;
begin
  if new.job is distinct from 'PRESIDENT' and new.sal is not null then
    select max(sal) into v_max from hr.emp where job = 'PRESIDENT' and empno <> new.empno;
    if new.sal >= v_max then
      raise exception 'Salary must stay below the president''s salary (%).', v_max
        using column = 'sal';
    end if;
  end if;
  return new;
end
$$;

create trigger emp_check_salary before insert or update of sal, job on hr.emp
  for each row execute function hr.check_salary();

-- Notifications are written for OTHER users, which the notification RLS
-- policy would forbid; security definer runs the insert as the table owner.
create function hr.notify_leave_requested() returns trigger
language plpgsql security definer set search_path = hr, pg_catalog as $$
begin
  insert into hr.notification (username, message)
  select m.username, format('%s requested %s day(s) of leave from %s.',
                            e.ename, new.days, to_char(new.start_date, 'DD Mon YYYY'))
    from hr.emp e join hr.emp m on m.empno = e.mgr
   where e.empno = new.empno and m.username is not null;
  return new;
end
$$;

create function hr.notify_leave_decided() returns trigger
language plpgsql security definer set search_path = hr, pg_catalog as $$
begin
  if new.status in ('APPROVED', 'REJECTED') then
    insert into hr.notification (username, message)
    select e.username, format('Your leave from %s to %s was %s by %s.',
                              to_char(new.start_date, 'DD Mon'), to_char(new.end_date, 'DD Mon'),
                              lower(new.status), new.decided_by)
      from hr.emp e
     where e.empno = new.empno and e.username is not null;
  end if;
  return new;
end
$$;

create trigger leave_requested after insert on hr.leave_request
  for each row execute function hr.notify_leave_requested();
create trigger leave_decided after update of status on hr.leave_request
  for each row when (old.status is distinct from new.status)
  execute function hr.notify_leave_decided();

