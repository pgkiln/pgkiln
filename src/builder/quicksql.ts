import type { FastifyInstance, FastifyReply } from 'fastify';
import { owner } from '../db.ts';
import { html } from '../html.ts';
import { icon } from '../icons.ts';
import { quickSql } from '../quicksql.ts';
import { clientIp, type Session } from '../session.ts';
import { runAndRecord, runOptions, SCRIPT_MAX_MB } from './scripts.ts';
import { back, BASE, csrf, developer, flash, region, send, shell, workshopTabs, type Req } from './ui.ts';
import { currentWorkspace } from './workspaces.ts';
import { tr } from './i18n.ts';

// SQL Workshop → Quick SQL: shorthand → DDL preview, then save it as a SQL
// script or run it (as a script, so the results per statement are kept).

const EXAMPLE = `# pk: identity
departments /auditcols
  name /nn /unique
  location
  employees
    name /nn vc100
    email /lower /unique
    job
    hired_on
    salary num(10,2)
    status /check active, on_leave, left /default active
view department_employees departments employees
`;

export async function quickSqlRoutes(app: FastifyInstance) {
  const render = (s: Session, reply: FastifyReply, src: string, body: Record<string, string | undefined>, error?: string) => {
    const tx = tr(s);
    const { ddl, warnings } = quickSql(src);
    const syntax = html`<details class="u-mt1"><summary>${tx('qs.syntax')}</summary><ul class="small">
        ${(['qs.syntax.tables', 'qs.syntax.types', 'qs.syntax.directives', 'qs.syntax.settings', 'qs.syntax.views'] as const).map((k) => html`<li>${tx.code(k)}</li>`)}</ul></details>`;
    const main = html`<form method="post" action="${BASE}/sql/quick">${csrf(s)}
      ${error ? html`<div class="alert alert-error" role="alert">${error}</div>` : ''}
      <div class="qs-columns">
        ${region(tx('sql.tool.quicksql'), html`<label class="sr-only" for="f_source">${tx('sql.tool.quicksql')}</label>
          <textarea id="f_source" name="source" class="code" rows="22" spellcheck="false">${src}</textarea>
          <div class="buttons"><button class="btn" name="action" value="preview">${icon('play')} ${tx('qs.generate')}</button></div>${syntax}`)}
        ${region('PostgreSQL', html`${warnings.length
            ? html`<div class="alert alert-error" role="alert"><ul class="u-m0">${warnings.map((w) => html`<li>${tx('qs.line', { line: w.line, message: w.message })}</li>`)}</ul></div>`
            : ''}
          <pre class="source ddl" data-code-view="sql" tabindex="0" aria-label="${tx('qs.generated')}">${ddl}</pre>`)}
      </div>
      <div class="u-spacer"></div>
      ${region(tx('qs.save_or_run'), html`<div class="form-grid"><div class="field"><label class="label" for="f_name">${tx('qs.script_name')}</label>
          <input id="f_name" name="name" value="${body.name ?? 'Quick SQL'}" maxlength="200"></div></div>
        ${runOptions(body, tx)}
        <div class="buttons"><button class="btn" name="action" value="save">${icon('file')} ${tx('qs.save_script')}</button>
          <button class="btn btn-hot" name="action" value="run">${icon('play')} ${tx('qs.run')}</button></div>`)}
    </form>`;
    return send(reply, s, shell(s, tx('sql.tool.quicksql'), [[tx('rail.sql_workshop'), `${BASE}/sql`], [tx('sql.tool.quicksql')]], html`<h1 class="u-mb1">${tx('rail.sql_workshop')}</h1>${workshopTabs('quicksql', s)}${main}`, 'sql'));
  };

  app.get(`${BASE}/sql/quick`, async (req: Req, reply) => {
    const s = await developer(req, reply);
    if (!s) return;
    return render(s, reply, EXAMPLE, {});
  });

  app.post(`${BASE}/sql/quick`, async (req: Req, reply) => {
    const s = await developer(req, reply);
    if (!s) return;
    const b = req.body ?? {};
    const src = (b.source ?? '').replace(/\r\n/g, '\n');
    if (Buffer.byteLength(src) > 1024 * 1024) {
      reply.code(422);
      return render(s, reply, '', b, tr(s)('qs.too_large'));
    }
    if (b.action !== 'save' && b.action !== 'run') return render(s, reply, src, b);
    const { ddl } = quickSql(src);
    const content = `-- Generated by Quick SQL\n${src
      .split('\n')
      .map((l) => `-- ${l}`.trimEnd())
      .join('\n')}\n\n${ddl}`;
    if (Buffer.byteLength(content) > SCRIPT_MAX_MB * 1024 * 1024) {
      reply.code(422);
      return render(s, reply, src, b, tr(s)('qs.script_too_large'));
    }
    const name = (b.name ?? '').trim().slice(0, 200) || 'Quick SQL';
    if (b.action === 'run') {
      const { id } = await runAndRecord(s, clientIp(req), { scriptId: null, name, content: ddl, stopOnError: b.on_error !== 'continue', transaction: b.transaction === 'true' });
      return back(reply, s, `${BASE}/sql/scripts/runs/${id}`);
    }
    let unique = name;
    for (let n = 2; await owner.one('select 1 from meta.sql_script where name = $1 and workspace_id = $2', [unique, currentWorkspace(s)]); n++) unique = `${name} (${n})`;
    const r = await owner.one(`insert into meta.sql_script (name, content, created_by, updated_by, workspace_id) values ($1, $2, $3, $3, $4) returning id`, [unique, content, s.username, currentWorkspace(s)]);
    flash(s, tr(s)('qs.saved', { name: unique }));
    return back(reply, s, `${BASE}/sql/scripts/${r!.id}`);
  });
}

