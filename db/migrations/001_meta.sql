-- =====================================================================
-- pgapex metadata repository
--
-- Every application is data: an app owns shared components (navigation,
-- authorization schemes, application items and processes, users) and pages;
-- pages own regions, items, buttons, dynamic actions, validations and
-- processes. The runtime (src/runtime) renders these rows; the builder
-- (src/builder) edits them. Everything here can be scripted with SQL.
-- =====================================================================

create extension if not exists pgcrypto;

create schema meta;

-- Instance-wide secrets. Only the owner (builder/migrations) can read this.
create table meta.instance_setting (
  name  text primary key,
  value text not null
);
insert into meta.instance_setting values ('url_secret', encode(gen_random_bytes(32), 'hex'));

-- ---------------------------------------------------------------------
-- Application and shared components
-- ---------------------------------------------------------------------

create table meta.app (
  id           serial primary key,
  alias        text not null unique check (alias ~ '^[a-z][a-z0-9_-]*$'),
  name         text not null,
  home_page    int  not null default 1,
  -- 'none'      : public app, APP_USER = 'nobody'
  -- 'app_users' : users in meta.app_user, login page at /a/<alias>/login
  authentication text not null default 'app_users' check (authentication in ('none', 'app_users')),
  -- The "parsing schema": all developer SQL runs under SET LOCAL ROLE
  -- <db_role>, so Postgres grants and row level security apply.
  db_role      text,
  -- Show database error details to end users (development only).
  debug        boolean not null default false,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- Authorization schemes, referenced by name from components. Prefix a
-- reference with '!' to negate it. MUST_NOT_BE_PUBLIC_USER is built in.
create table meta.authz_scheme (
  id            serial primary key,
  app_id        int  not null references meta.app on delete cascade,
  name          text not null check (name ~ '^[A-Z][A-Z0-9_]*$'),
  -- role : the user has the role in meta.app_user.roles (value = role name)
  -- sql  : value is a SQL boolean expression (binds allowed)
  type          text not null check (type in ('role', 'sql')),
  value         text not null,
  error_message text not null default 'You are not authorized to access this page.',
  unique (app_id, name)
);

-- Application items: session state that is not on any page and can only be
-- set by server-side code (application/page processes), never by the browser.
create table meta.app_item (
  id          serial primary key,
  app_id      int  not null references meta.app on delete cascade,
  name        text not null check (name ~ '^[A-Z][A-Z0-9_]*$'),
  description text,
  unique (app_id, name)
);

create table meta.app_process (
  id            serial primary key,
  app_id        int  not null references meta.app on delete cascade,
  seq           int  not null default 10,
  name          text not null,
  -- after_login : once, right after a successful login
  -- before_page : before every page is rendered or submitted
  point         text not null check (point in ('after_login', 'before_page')),
  code          text not null,
  authz         text
);

create table meta.nav_entry (
  id            serial primary key,
  app_id        int  not null references meta.app on delete cascade,
  parent_id     int  references meta.nav_entry on delete cascade,
  seq           int  not null default 10,
  label         text not null,
  icon          text,
  target_page   int,
  authz         text
);

-- ---------------------------------------------------------------------
-- Pages and page components
-- ---------------------------------------------------------------------

create table meta.page (
  id            serial primary key,
  app_id        int  not null references meta.app on delete cascade,
  page_no       int  not null check (page_no > 0),
  name          text not null,
  title         text,
  requires_auth boolean not null default true,
  -- breadcrumb parent
  parent_page   int,
  -- 'modal' pages open in a dialog over the calling page
  mode          text not null default 'normal' check (mode in ('normal', 'modal')),
  -- 'checksum': item values passed in the URL must carry a valid checksum
  -- (generated by the runtime), so users cannot tamper with e.g. ?P3_ID=
  protection    text not null default 'checksum' check (protection in ('unrestricted', 'checksum')),
  authz         text,
  unique (app_id, page_no)
);

create table meta.region (
  id            serial primary key,
  page_id       int  not null references meta.page on delete cascade,
  seq           int  not null default 10,
  title         text,
  -- report : source is a SELECT; interactive table (sort, search, filter, CSV)
  -- form   : items bound to columns of table_name, keyed by pk_column/pk_item
  -- chart  : source is a SELECT returning (label, value)
  -- cards  : source is a SELECT with columns title, subtitle, body, badge, icon
  -- static : source is HTML; &ITEM. placeholders are replaced (escaped)
  type          text not null check (type in ('report', 'form', 'chart', 'cards', 'static')),
  source        text,
  table_name    text,
  pk_column     text,
  pk_item       text,
  -- 12-column grid, like the Universal Theme
  columns       int  not null default 12 check (columns between 1 and 12),
  template      text not null default 'standard' check (template in ('standard', 'plain', 'collapsible')),
  -- SQL boolean expression; the region renders only when true
  condition     text,
  authz         text,
  config        jsonb not null default '{}'
);

create table meta.item (
  id                 serial primary key,
  page_id            int  not null references meta.page on delete cascade,
  region_id          int  references meta.region on delete cascade,
  seq                int  not null default 10,
  -- Items are session-state variables, referenced as :NAME in any SQL.
  -- Convention (as in APEX): P<page>_<NAME>.
  name               text not null check (name ~ '^[A-Z][A-Z0-9_]*$'),
  label              text,
  type               text not null default 'text' check (type in
                       ('text', 'textarea', 'number', 'date', 'datetime', 'select', 'radio',
                        'checkbox', 'switch', 'hidden', 'display', 'password')),
  -- select/radio lists: a SELECT returning (display, return), or
  -- 'STATIC:Display;Return,Other;OTHER'
  lov                text,
  source_column      text,
  default_value      text,
  required           boolean not null default false,
  help               text,
  -- SQL boolean expression; when true the item renders read-only and is
  -- not accepted on submit
  readonly_condition text,
  authz              text,
  -- {"submit_on_change": true, "null_label": "- All -", "cascade_parents": "P3_DEPTNO"}
  config             jsonb not null default '{}',
  unique (page_id, name)
);

create table meta.button (
  id            serial primary key,
  page_id       int  not null references meta.page on delete cascade,
  region_id     int  references meta.region on delete cascade,
  seq           int  not null default 10,
  -- the REQUEST value; processes/validations filter on it
  name          text not null check (name ~ '^[A-Z][A-Z0-9_]*$'),
  label         text not null,
  -- submit   : submits the page with REQUEST = name
  -- redirect : link to target_page (with target_items)
  -- da       : does nothing by itself; a dynamic action handles the click
  action        text not null default 'submit' check (action in ('submit', 'redirect', 'da')),
  target_page   int,
  target_items  jsonb not null default '{}',
  -- SQL boolean expression. Evaluated when rendering AND again on submit,
  -- so a hidden button cannot be "pressed" by a forged request.
  condition     text,
  authz         text,
  hot           boolean not null default false,
  confirm       text
);

create table meta.dynamic_action (
  id                 serial primary key,
  page_id            int  not null references meta.page on delete cascade,
  seq                int  not null default 10,
  name               text not null,
  event              text not null default 'change' check (event in ('change', 'click', 'load')),
  -- item name(s) (comma separated) for change, button name for click
  trigger_element    text,
  -- client-side condition on the triggering item's value
  condition_type     text check (condition_type in ('equals', 'not_equals', 'in_list', 'is_null', 'is_not_null')),
  condition_value    text,
  -- show/hide/enable/disable : client side, reversed when the condition is false
  -- set_value      : code is a SELECT; its columns set affected_items
  -- execute_sql    : run code; returned columns named like items set them
  -- refresh_region : re-render affected_region_id
  -- refresh_item   : re-render affected_items (e.g. dependent lists)
  -- alert / submit : client side
  action             text not null check (action in ('show', 'hide', 'enable', 'disable', 'set_value',
                       'execute_sql', 'refresh_region', 'refresh_item', 'alert', 'submit')),
  affected_items     text,
  affected_region_id int references meta.region on delete set null,
  code               text,
  -- items whose browser values are sent to the server first
  items_to_submit    text,
  message            text,
  authz              text
);

create table meta.validation (
  id           serial primary key,
  page_id      int  not null references meta.page on delete cascade,
  seq          int  not null default 10,
  name         text not null,
  -- item the error is attached to; null = page-level error
  item_name    text,
  -- not_null : item must have a value
  -- sql      : expression is a SQL boolean expression that must be true
  -- regex    : item value must match expression (POSIX, checked in Postgres)
  type         text not null check (type in ('not_null', 'sql', 'regex')),
  expression   text,
  message      text not null,
  when_button  text
);

create table meta.process (
  id              serial primary key,
  page_id         int  not null references meta.page on delete cascade,
  seq             int  not null default 10,
  name            text not null,
  -- form_dml : insert/update/delete the form region's table from its items
  -- sql      : run code (SQL with :BINDS). If it returns a row, columns
  --            named like items (page or application items) set them.
  type            text not null check (type in ('form_dml', 'sql')),
  region_id       int  references meta.region on delete cascade,
  code            text,
  -- 'submit' runs after validations on POST; 'load' runs before rendering
  point           text not null default 'submit' check (point in ('submit', 'load')),
  when_button     text,
  authz           text,
  success_message text
);

